package Literals;
public class IntegralsLiteralForms{
    public static void main(String[] args){
        int decimal=10;
        int octal=010;
        int hexadecimal=0X10;
        int binary=0b10;
        //Here we are given same number in different forms//
        System.out.println("Decimal Form of 10 is :" +decimal);
        System.out.println("Octal Form of 10 is : "+octal);
        System.out.println("Hexadecimal Form of 10 is: "+hexadecimal);
        System.out.println("Binary Form of 10 is :"+binary);
    }
}